import { provideHttpClient } from '@angular/common/http';
import { HttpTestingController, provideHttpClientTesting } from '@angular/common/http/testing';
import { TestBed } from '@angular/core/testing';
import { describe, expect, it, vi } from 'vitest';
import { AiPhotoPanel } from './ai-photo';

describe('AI photo preview', () => {
  it('requires consent and renders the completed local effect', async () => {
    TestBed.configureTestingModule({ providers: [provideHttpClient(), provideHttpClientTesting()] });
    const fixture = TestBed.createComponent(AiPhotoPanel);
    fixture.componentRef.setInput('photo', { id: 'original', width: 60, height: 40, byte_size: 100 });
    const http = TestBed.inject(HttpTestingController);
    const endpoint = '/api/sessions/current/photos/ai';
    const provider = { label: 'Local preview', sends_photo: false, privacy_url: null };
    const template = { id: 'cinematic-portrait', name: 'Cinematic portrait', description: 'Cool shadows.' };
    fixture.detectChanges();
    const toggle = fixture.nativeElement.querySelector('.effect-toggle') as HTMLButtonElement;
    expect(toggle.getAttribute('aria-expanded')).toBe('false');
    toggle.click();
    http.expectOne(endpoint + '?asset_id=original').flush({ provider, templates: [{ ...template, job: null }] });
    await fixture.whenStable();
    fixture.detectChanges();
    expect(toggle.getAttribute('aria-expanded')).toBe('true');
    const apply = fixture.nativeElement.querySelector('.effect-content button.primary') as HTMLButtonElement;
    expect(apply.disabled).toBe(true);
    expect(fixture.nativeElement.textContent).toContain('on this computer');
    apply.click();
    http.expectNone(endpoint);
    fixture.nativeElement.querySelector('input').click();
    fixture.detectChanges();
    apply.click();
    const queued = http.expectOne(endpoint);
    expect(queued.request.method).toBe('POST');
    expect(queued.request.body).toEqual({ asset_id: 'original', template_id: template.id, consent: true });
    const job = { id: 'effect', template_id: template.id, state: 'queued', detail: 'Waiting to process your photo.' };
    queued.flush(job);
    await fixture.whenStable();
    fixture.detectChanges();
    expect(fixture.nativeElement.textContent).toContain(job.detail);
    const printEndpoint = '/api/sessions/current/photos/print-jobs';
    http.expectNone(request => request.url === printEndpoint);
    expect(fixture.nativeElement.textContent).not.toContain('Print effect');
    expect(fixture.nativeElement.textContent).not.toContain('Download effect on phone');
    const refreshed = fixture.componentInstance.refresh();
    http.expectOne(endpoint + '?asset_id=original').flush({ provider, templates: [{
      ...template, job: { ...job, state: 'completed', detail: 'Your photo effect is ready.' },
    }] });
    await refreshed;
    fixture.detectChanges();
    http.expectOne(printEndpoint + '?asset_id=effect&kind=effect').flush(null);
    await fixture.whenStable();
    fixture.detectChanges();
    const img = fixture.nativeElement.querySelector('img') as HTMLImageElement;
    const download = fixture.nativeElement.querySelector('a[download]') as HTMLAnchorElement;
    expect(img.getAttribute('src')).toBe(endpoint + '/effect/preview');
    expect(download.getAttribute('href')).toBe(endpoint + '/effect/download');
    const buttons = Array.from(fixture.nativeElement.querySelectorAll('button') as NodeListOf<HTMLButtonElement>);
    const phone = buttons.find(button => button.textContent?.trim() === 'Download effect on phone')!;
    phone.click();
    const share = http.expectOne('/api/sessions/current/photos/phone-links');
    expect(share.request.method).toBe('POST');
    expect(share.request.body).toEqual({ asset_id: job.id, kind: 'effect' });
    const qr = 'data:image/png;base64,aW1hZ2U=';
    share.flush({ url: 'http://192.168.42.7:8001/d/effect', qr_image: qr, expires_at: '2026-11-18T00:10:00Z' });
    await fixture.whenStable();
    fixture.detectChanges();
    const qrImage = fixture.nativeElement.querySelector('[aria-label="Processed photo phone download"] img');
    expect(qrImage.getAttribute('src')).toBe(qr);
    const print = buttons.find(button => button.textContent?.trim() === 'Print effect')!;
    expect(print.textContent?.trim()).toBe('Print effect');
    await vi.waitFor(() => {
      fixture.detectChanges();
      expect(print.disabled).toBe(false);
    });
    print.click();
    const submission = http.expectOne(printEndpoint);
    expect(submission.request.method).toBe('POST');
    expect(submission.request.body).toEqual({ asset_id: job.id, kind: 'effect' });
    submission.flush({ id: 'effect-print', state: 'sent', detail: 'Sent to the printer.' });
    await fixture.whenStable();
    fixture.detectChanges();
    expect(fixture.nativeElement.textContent).toContain('Sent to the printer.');
    toggle.click();
    fixture.detectChanges();
    expect((fixture.nativeElement.querySelector('.effect-content') as HTMLElement).hidden).toBe(true);
    toggle.click();
    fixture.detectChanges();
    expect(qrImage.getAttribute('src')).toBe(qr);
    http.verify();
    fixture.destroy();
  });
});
